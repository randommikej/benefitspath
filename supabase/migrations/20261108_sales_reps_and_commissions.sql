-- Sales reps, commission ledger and payouts for the 1099 rep program.
-- Additive only: creates three tables and adds attorneys.rep_id. Nothing is dropped or rewritten.

create table if not exists reps (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  name        text not null,
  email       text,
  phone       text,
  code        text not null unique,
  active      boolean not null default true,
  notes       text
);

alter table attorneys add column if not exists rep_id bigint references reps(id);
create index if not exists attorneys_rep_id_idx on attorneys(rep_id);
create index if not exists attorneys_stripe_subscription_id_idx on attorneys(stripe_subscription_id);

create table if not exists rep_payouts (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  rep_id        bigint not null references reps(id),
  amount_cents  integer not null,
  method        text,
  note          text
);

-- One row per paid Stripe invoice on a rep-credited listing ($100 each).
-- payout_id stays null until the commission is included in a payout.
create table if not exists commissions (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default now(),
  stripe_invoice_id  text not null unique,
  attorney_id        bigint references attorneys(id),
  rep_id             bigint not null references reps(id),
  amount_cents       integer not null default 10000,
  invoice_paid_at    timestamptz,
  payout_id          bigint references rep_payouts(id)
);
create index if not exists commissions_rep_unpaid_idx on commissions(rep_id) where payout_id is null;

-- Server-only tables: the API reads and writes them with the service role key.
alter table reps enable row level security;
alter table rep_payouts enable row level security;
alter table commissions enable row level security;
